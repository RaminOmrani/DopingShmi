/** تعداد رقم اعشار یک عدد (برای قاعده‌ی رقم‌های بامعنا در جمع) */
export function decimalsOf(x: number): number {
  const s = String(x);
  if (/e/i.test(s)) return 0;
  const dot = s.indexOf(".");
  return dot < 0 ? 0 : s.length - dot - 1;
}
