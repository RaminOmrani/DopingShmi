/**
 * مدل داده‌ی برگه‌ی فرمول‌های شیمی (/formul-shimi).
 * همه‌ی متن‌ها با نشانه‌گذاری ChemText نوشته می‌شوند: {{فرمول یا عدد با یکا}} و **پررنگ**.
 * قاعده‌ها: فقط رابطه‌هایی که در کتاب درسی فعلی هستند؛ عددهای مثال دو بار حساب شده‌اند؛ متن و مثال‌ها نوشته‌ی خود
 * دوپینگ شیمی است (نه رونوشت کتاب یا ناشران). هر {{…}} کوتاه (حدود ۳۰ نویسه) تا در گوشی بیرون نزند.
 */
import type { GradeKey } from "../../lib/syllabus";
import type { ToolKey } from "../../lib/site-routes";

/** متن فارسی با نشانه‌گذاری ChemText */
export type Rich = string;

/** یک متغیر رابطه */
export interface FormulaVar {
  /** نماد یا نام متغیر (Rich؛ نماد لاتین داخل {{}}) */
  sym: Rich;
  /** معنی متغیر */
  desc: Rich;
  /** یکا با نشانه‌گذاری Chem و بدون {{}}، مثل «g/mol»؛ برای کمیت بی‌یکا خالی */
  unit?: string;
}

/** یک رابطه یا فرمول در برگه */
export interface FormulaItem {
  /** شناسه‌ی لاتین یکتا برای لنگر (حروف کوچک و خط تیره) */
  id: string;
  /** نام رابطه (اصطلاح کتاب درسی + عبارت جست‌وجو) */
  name: Rich;
  /**
   * شکل نمادین با نشانه‌گذاری Chem (چپ‌به‌راست)؛ کنار « = » می‌شکند تا در گوشی جا شود.
   * اگر پیکان داشته باشد، به‌صورت معادله (Eq) نمایش داده می‌شود.
   */
  f?: string;
  /** شکل‌های نمادین کمکی (هر کدام یک سطر کوچک‌تر) */
  alt?: string[];
  /** شکل کلامی (راست‌به‌چپ، Rich)؛ برای رابطه‌هایی که کتاب با کلمه می‌نویسد */
  words?: Rich;
  vars: FormulaVar[];
  /** چه وقت به کار می‌رود */
  when: Rich;
  /** یک مثال یک‌خطی */
  example: Rich;
  /** هشدار یا شرط کوتاه (اختیاری) */
  note?: Rich;
  /** جدول کیفی (فقط برای اصل لوشاتلیه) */
  table?: { head: string[]; rows: Rich[][] };
  /** ابزار مرتبط؛ اگر نباشد، رابطه به صفحه‌ی فصل خودش لینک می‌شود */
  tool?: ToolKey;
}

/** رابطه‌های یک فصل */
export interface FormulaChapter {
  grade: GradeKey;
  n: number;
  items: FormulaItem[];
}

/** رابطه‌های یک پایه */
export interface FormulaGrade {
  grade: GradeKey;
  /** شناسه‌ی لنگر بخش پایه، مثل «dahom» */
  id: string;
  /** یک جمله درباره‌ی رابطه‌های این پایه */
  lead: Rich;
  chapters: FormulaChapter[];
}
