async function seedV2() {
  if (await db.setting.findUnique({ where: { key: MARK_V2 } })) return;
  let created = 0;
  for (const a of ARTICLES_V2) {
    if (await db.article.findUnique({ where: { slug: a.slug } })) continue;
    await db.article.create({ data: { ...a, published: false } });
    created++;
  }
  await db.setting.create({ data: { key: MARK_V2, value: { at: new Date().toISOString(), created } } });
  if (created) console.log(`✔ ${created} مقاله‌ی تازه به‌صورت پیش‌نویس ساخته شد (پنل مدیریت ← مقالات)`);
}

